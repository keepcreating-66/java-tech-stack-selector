function prompt(config: TechStackConfig): string {
    if (config.outputMode === 'prompt') {
        const structure = config.project.type === 'monolith' ? '一个可执行 Maven 应用，按业务域组织代码。'
            : config.project.type === 'modular-monolith' ? 'Maven 聚合父工程、common 公共模块、独立业务模块和 bootstrap 启动模块；只有 bootstrap 为可执行应用。'
            : `Maven 聚合父工程、各业务域独立的服务应用与配置、不同默认端口；${config.microservice?.gateway ? '包含静态地址路由网关。' : '不包含网关。'}`;
        return `# 项目创建提示词

本文件仅导出了提示词，尚未创建工程。请按以下已确认配置创建 Java 后端项目，不要改换架构或加入未选择的组件。

结构要求：${structure}

\`\`\`json
${JSON.stringify(config, null, 2)}
\`\`\`

先检查目标路径；不要覆盖已有工程。实际写出所选 ORM 的实体、仓储、服务与接口、健康端点、环境变量配置、运行说明和测试。完成后分别报告文件创建状态和实际构建、运行验证结果。
`;
    }
    return `# 项目后续完善提示词

项目 ${config.project.name} 已生成 ${config.project.type} 架构的基础工程，业务模块为 ${config.project.modules?.join(', ')}。
构建工具 ${config.project.buildTool}，Java ${config.project.javaVersion}，框架 ${config.core.framework}，数据库 ${config.database.rdbms}，ORM ${config.database.orm}，缓存 ${config.cache.type}，认证 ${config.security.framework}。
请先读取 tech-stack-config.json、README.md 和已有代码，保留所选架构与真实模块边界，再按用户业务需求完善业务规则、测试和部署。不要把架构改写成其他类型。
`;
}

/** Pure production renderer. All enabled options must be validated before any file is written. */
export function planProject(input: TechStackConfig): ProjectPlan {
    assertConfigShape(input);
    const config = normal(input);
    assertValidConfig(config);
    const files: Record<string, string> = {
        'tech-stack-config.json': JSON.stringify(config, null, 2) + '\n'
    };
    if (config.outputMode === 'config') { return { projectName: config.project.name, config, files }; }
    files['project-prompt.md'] = prompt(config);
    if (config.outputMode === 'prompt') { return { projectName: config.project.name, config, files: { 'project-prompt.md': files['project-prompt.md'] } }; }
    Object.assign(files, sql(config), config.project.type === 'monolith' ? monolith(config)
        : config.project.type === 'modular-monolith' ? modular(config) : microservice(config));
    files['README.md'] = readme(config);
    files['.env.example'] = `# 将变量导入当前终端后启动；Spring Boot 不会自动读取此文件。\n# DB_URL 未设置时使用 application.yml 的默认地址；不要导出空 DB_URL。\n# DB_URL=jdbc:...\nDB_USER=app\nDB_PASSWORD=\n${config.cache.type === 'redisson' ? 'REDIS_HOST=localhost\nREDIS_PORT=6379\n' : ''}${config.security.framework === 'sa-token' ? 'DEMO_USER=\nDEMO_PASSWORD=\n' : ''}`;
    files['.gitignore'] = 'target/\n**/target/\n.idea/\n.vscode/\n.env\n.DS_Store\n';
    return { projectName: config.project.name, config, files };
}
